import { describe, expect, it } from 'vitest';
import type { AvailabilityFact } from '../resources/availability';
import { localMs, resolveRecurring } from '../resources/zoned';
import { evaluateSchedule } from './engine';
import { ALWAYS_OPEN, spec, World } from './engine.fixture';
import type { SchedulingRequirement } from './profile';
import { proposeSchedule } from './proposal';

/**
 * ADR-0075 § 10: the breakpoint domain is claimed (by reasoning, not proof) to contain the earliest
 * feasible start. This property test checks the claim on small generated fixtures against an
 * EXHAUSTIVE whole-second search whose only feasibility authority is `evaluateSchedule` — the same
 * acceptance rule (no HARD conflict and no AVAILABILITY_UNDECLARED involving the candidate), no
 * second conflict engine. Fixtures are generated by a seeded PRNG, so the test is deterministic.
 *
 * Every fixture's 45-minute horizon straddles local midnight in a (mostly non-UTC) event zone, with daily
 * limits, rest, changeover, dependency lead and availability that is continuous, crosses local
 * midnight, or opens only after it.
 */

/** mulberry32: a tiny deterministic PRNG (test data only). */
function prng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4_294_967_296;
  };
}

const ZONES = ['UTC', 'America/New_York', 'America/Costa_Rica', 'Asia/Tokyo'] as const;
const HORIZON_S = 2_700;

interface Fixture {
  readonly w: World;
  readonly lo: number;
  readonly hi: number;
  readonly durationMs: number;
  readonly changeoverS: number;
}

function fixture(seed: number): Fixture {
  const rnd = prng(seed);
  const pick = <T>(xs: readonly T[]): T => xs[Math.floor(rnd() * xs.length)] as T;
  const int = (lo: number, hi: number) => lo + Math.floor(rnd() * (hi - lo + 1));

  const zone = pick(ZONES);
  // The window opens at 23:40 local on 2026-11-14 for 45 minutes: it crosses local midnight.
  const lo = resolveRecurring(localMs('2026-11-14', '23:40') as number, zone);
  const hi = lo + HORIZON_S * 1000;
  const durationS = pick([300, 600, 737]);
  const changeoverS = pick([0, 120, 157]);
  const requirement: Partial<SchedulingRequirement> = {
    expectedDurationSeconds: durationS,
    changeoverSeconds: changeoverS,
    ...(rnd() < 0.5
      ? { rest: { minimumSeconds: pick([300, 667]), enforcement: pick(['HARD', 'SOFT'] as const) } }
      : {}),
    ...(rnd() < 0.4 ? { dependencyLeadSeconds: pick([120, 301]) } : {}),
    ...(rnd() < 0.7
      ? { maxUnitsPerEntrantPerDay: { value: 1, enforcement: pick(['HARD', 'SOFT'] as const) } }
      : {}),
  };

  const w = new World(false);
  w.competitionTimezone = zone;
  w.event('e1', { profile: spec(requirement), timezone: zone, windowStartMs: lo, windowEndMs: hi });
  const resources = rnd() < 0.6 ? 1 : 2;
  for (let i = 1; i <= resources; i++) w.resource(`c${i}`, { zone });

  // Availability (competition layer, event zone): continuous, crossing local midnight, or only
  // declared after midnight; sometimes a blackout on one court.
  const availability = pick(['continuous', 'crossing', 'after-midnight'] as const);
  const facts: AvailabilityFact[] =
    availability === 'continuous'
      ? [...ALWAYS_OPEN]
      : availability === 'crossing'
        ? [1, 2, 3, 4, 5, 6, 7].map((weekday) => ({
            kind: 'WEEKLY' as const,
            weekday,
            start: '23:45',
            end: '00:20',
          }))
        : [{ kind: 'DATE_OPEN' as const, date: '2026-11-15', start: '00:00', end: '01:00' }];
  facts.forEach((fact, i) => w.fact(`f${i}`, null, fact));
  if (rnd() < 0.3) {
    const s = lo + int(0, HORIZON_S - 300) * 1000;
    w.fact('bo', 'c1', {
      kind: 'BLACKOUT',
      startsAt: s,
      endsAt: s + int(120, 1_200) * 1000,
      reason: 'works',
    });
  }

  for (const e of ['a', 'b', 'c', 'z']) w.entrant(e);
  // Preserved content: 0–3 contests in an earlier round, some of them with the target's entrant.
  const existing = int(0, 3);
  for (let i = 0; i < existing; i++) {
    const start = lo - 600_000 + int(0, HORIZON_S) * 1000;
    w.contest(`x${i}`, {
      round: 'r0',
      roundSeq: 0,
      entrants: [pick(['a', 'b']), pick(['c', 'z'])],
    });
    w.assign(`x${i}`, {
      resource: `c${int(1, resources)}`,
      startMs: start,
      endMs: start + int(3, 15) * 60_000,
      changeover: changeoverS,
    });
  }
  w.contest('m1', { status: 'PLANNED', round: 'r1', roundSeq: 1, entrants: ['a', 'z'] });
  if (existing > 0 && rnd() < 0.4) w.place('m1', 3, { feeders: ['x0'] });
  return { w, lo, hi, durationMs: durationS * 1000, changeoverS };
}

/** The exhaustive answer: the first whole second (then resource id) the JUDGE accepts. */
function exhaustive(f: Fixture): { start: number; resourceId: string } | null {
  const judge = f.w.input();
  const resources = [...judge.resources].map((r) => r.id).sort();
  for (let t = f.lo; t + f.durationMs <= f.hi; t += 1000)
    for (const resourceId of resources) {
      const candidate = {
        id: 'proposal:m1',
        contestId: 'm1',
        resourceId,
        startMs: t,
        expectedEndMs: t + f.durationMs,
        changeoverSeconds: f.changeoverS,
        recordedUnitKey: 'contest:m1',
      };
      const report = evaluateSchedule({
        ...judge,
        watermark: [...judge.watermark, candidate.id],
        assignments: [...judge.assignments, candidate],
      });
      const blocked = report.conflicts.some(
        (c) =>
          (c.severity === 'HARD' || c.code === 'AVAILABILITY_UNDECLARED') &&
          c.assignmentIds.includes(candidate.id),
      );
      if (!blocked) return { start: Math.floor(t / 1000), resourceId };
    }
  return null;
}

const SEEDS = Array.from({ length: 16 }, (_, i) => 1_000 + i * 7_919);

describe('breakpoint completeness vs exhaustive whole-second search (ADR-0075 § 10)', () => {
  it.each(SEEDS)(
    'seed %i: the greedy start is the earliest the judge accepts',
    (seed) => {
      const f = fixture(seed);
      const p = proposeSchedule({
        judge: f.w.input(),
        draftStatus: 'DRAFT',
        competitionStatus: 'IN_PROGRESS',
        basePublishedVersionId: null,
        eventStatuses: [{ eventId: 'e1', status: 'FIELD_LOCKED' }],
        latestOffsets: f.w.contests.map((c) => ({ contestId: c.id, seconds: 0 })),
      });
      const expected = exhaustive(f);
      const got = p.placements[0];
      if (expected === null) {
        expect(got).toBeUndefined();
        expect(p.status).not.toBe('SUCCESS');
      } else {
        expect({ start: got?.start, resourceId: got?.resourceId }).toEqual(expected);
      }
    },
    120_000,
  );

  it('the generated fixtures exercise every intended dimension', () => {
    const fixtures = SEEDS.map(fixture);
    const zones = new Set(fixtures.map((f) => f.w.events[0]?.timezone));
    expect(zones.size).toBeGreaterThanOrEqual(3);
    const limited = fixtures.filter((f) =>
      f.w.events[0]?.profile?.spec.requirements.some(
        (r) => r.maxUnitsPerEntrantPerDay !== undefined,
      ),
    );
    expect(limited.length).toBeGreaterThanOrEqual(6);
    const kinds = new Set(
      fixtures.map((f) =>
        f.w.availability
          .map((a) => a.fact.kind)
          .sort()
          .join(','),
      ),
    );
    expect(kinds.size).toBeGreaterThanOrEqual(3);
  });
});
